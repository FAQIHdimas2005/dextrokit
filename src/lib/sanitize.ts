/**
 * Input sanitization helpers shared by client components.
 *
 * Everything here is defense-in-depth: the UI never renders raw HTML from user
 * input, and these helpers stop dangerous URI schemes and control characters
 * from ever reaching a QR payload, a download, or the DOM.
 */

/** QR codes become unreliable to scan well before this. */
export const MAX_QR_PAYLOAD_LENGTH = 1200;

const ALLOWED_URI_SCHEMES = new Set(["http:", "https:"]);

const CONTROL_CHARS = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g;

export interface SanitizedResult {
  ok: boolean;
  value: string;
  error?: string;
}

/**
 * Removes NUL/control characters (except newlines and tabs, which are valid in
 * vCard and plain-text payloads) and normalizes line endings.
 */
export function stripControlCharacters(input: string): string {
  return input.replace(/\r\n?/g, "\n").replace(CONTROL_CHARS, "").trim();
}

/**
 * Returns true only for absolute http(s) URLs. `new URL` also rejects strings
 * such as `javascript:alert(1)`, but the scheme allowlist keeps the intent
 * explicit and blocks `data:`, `file:`, and `vbscript:` outright.
 */
export function isSafeHttpUrl(value: string): boolean {
  try {
    const url = new URL(value);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return false;
  }
}

export function hasDangerousScheme(value: string): boolean {
  const compact = value.replace(/[\s\u0000-\u001F]/g, "").toLowerCase();
  if (!compact) return false;

  // `java\tscript:` style obfuscation is caught after whitespace removal.
  return (
    compact.startsWith("javascript:") ||
    compact.startsWith("data:") ||
    compact.startsWith("vbscript:") ||
    compact.startsWith("file:")
  );
}

/**
 * Validates a URL typed into the QR generator. Bare domains get an `https://`
 * prefix; anything with a non-web scheme is rejected instead of being encoded
 * into the QR image.
 */
export function sanitizeUrlPayload(rawInput: string): SanitizedResult {
  const cleaned = stripControlCharacters(rawInput);

  if (!cleaned) {
    return { ok: false, value: "", error: "Enter a website URL to generate a QR code." };
  }

  if (hasDangerousScheme(cleaned)) {
    return {
      ok: false,
      value: "",
      error: "Only http and https links are supported. Remove the script or data prefix.",
    };
  }

  const withScheme = /^[a-z][a-z0-9+.-]*:/i.test(cleaned) ? cleaned : `https://${cleaned}`;

  let parsed: URL;
  try {
    parsed = new URL(withScheme);
  } catch {
    return { ok: false, value: "", error: "That doesn't look like a valid URL." };
  }

  if (!ALLOWED_URI_SCHEMES.has(parsed.protocol)) {
    return {
      ok: false,
      value: "",
      error: "Only http and https links are supported.",
    };
  }

  if (!parsed.hostname || !parsed.hostname.includes(".")) {
    return {
      ok: false,
      value: "",
      error: "Add a full domain, for example example.com.",
    };
  }

  if (withScheme.length > MAX_QR_PAYLOAD_LENGTH) {
    return { ok: false, value: "", error: "That URL is too long to fit in a scannable QR code." };
  }

  return { ok: true, value: withScheme };
}

/** Escapes a value for the `WIFI:` payload grammar. */
export function escapeWifiValue(value: string): string {
  return stripControlCharacters(value).replace(/([\\;,:"])/g, "\\$1");
}

/** Escapes a value for the vCard 3.0 grammar. */
export function escapeVCardValue(value: string): string {
  return stripControlCharacters(value)
    .replace(/\\/g, "\\\\")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,")
    .replace(/\n/g, "\\n");
}

/** Validates a plain-text / note payload. */
export function sanitizeTextPayload(rawInput: string): SanitizedResult {
  const cleaned = stripControlCharacters(rawInput);

  if (!cleaned) {
    return { ok: false, value: "", error: "Enter the text you want to encode." };
  }

  if (cleaned.length > MAX_QR_PAYLOAD_LENGTH) {
    return {
      ok: false,
      value: "",
      error: `Keep the text under ${MAX_QR_PAYLOAD_LENGTH} characters so the code stays scannable.`,
    };
  }

  return { ok: true, value: cleaned };
}

export function isValidEmail(value: string): boolean {
  const trimmed = value.trim();
  if (!trimmed || trimmed.length > 254) return false;
  // Pragmatic check: one @, no whitespace, a dot in the domain.
  return /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(trimmed);
}

export function isValidPhoneNumber(value: string): boolean {
  const trimmed = value.trim();
  if (!trimmed) return false;
  return /^\+?[0-9()[\]\s.-]{6,20}$/.test(trimmed);
}

/**
 * Last line of defense for SVG exports. The SVG is generated by
 * `qr-code-styling`, but a user-supplied logo is embedded inside it, so the
 * final markup is inspected before it is written to disk.
 */
export function assertSafeSvgMarkup(svg: string): void {
  const forbidden = [
    /<\s*script[\s>]/i,
    /<\s*foreignObject[\s>]/i,
    /<\s*iframe[\s>]/i,
    /<\s*use[^>]+href\s*=\s*["']\s*(?:javascript|data):/i,
    /\son[a-z]+\s*=/i,
    /javascript:/i,
    /<!ENTITY/i,
  ];

  for (const pattern of forbidden) {
    if (pattern.test(svg)) {
      throw new Error("The generated SVG failed a safety check and was not downloaded.");
    }
  }
}
